// Canonical schema -> wire bindings. Validate bounds/patterns with JSON Schema at boundaries.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
// The entire reference registry is local and explicit. Never fetch schema URLs.
const registry = new Map();
for (const [file, title] of [['suggestion', 'Suggestion'], ['analysis', 'AnalysisResult']]) {
  const schema = JSON.parse(await readFile(resolve(root, `packages/protocol/schema/${file}.schema.json`), 'utf8'));
  const id = `https://nexwrite.local/schema/${file}.schema.json`;
  if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema' || schema.$id !== id || schema.title !== title || !schema.$defs) throw new Error('Unsupported schema: canonical root metadata');
  registry.set(id, schema);
}
const header = '// SPDX-License-Identifier: LicenseRef-NexWrite-Proprietary\n// Generated by tools/codegen/generate.mjs. Do not edit.\n// Validate wire data with the canonical JSON Schema; types do not enforce every constraint.\n';
const quote = JSON.stringify;
const pascal = value => value.split('_').map(part => part[0].toUpperCase() + part.slice(1)).join('');
const numberNames = { 1: 'One', 2: 'Two', 3: 'Three' };
const fail = message => { throw new Error(`Unsupported schema: ${message}`); };
const entries = Object.entries;
const definitions = {};
const owners = new WeakMap();
function own(node, schema) {
  if (!node || typeof node !== 'object') return;
  owners.set(node, schema);
  for (const value of Object.values(node)) own(value, schema);
}
for (const schema of registry.values()) {
  own(schema, schema);
  for (const [name, node] of entries({ ...schema.$defs, [schema.title]: schema })) {
    if (Object.hasOwn(definitions, name) || Object.hasOwn(schema.$defs, schema.title)) fail(`duplicate type name ${name}`);
    definitions[name] = node;
  }
}
function reference(node) {
  const owner = owners.get(node);
  if (typeof node.$ref !== 'string' || !owner) fail('invalid reference');
  let url;
  try { url = new URL(node.$ref, owner.$id); } catch { fail('invalid reference URL'); }
  const fragment = url.hash;
  url.hash = '';
  const target = registry.get(url.href);
  if (!target) fail(`unregistered reference ${node.$ref}`);
  if (!fragment) return target.title;
  if (!/^#\/\$defs\/[A-Z][A-Za-z0-9]*$/.test(fragment) || !Object.hasOwn(target.$defs, fragment.slice(8))) fail(`unresolved reference ${node.$ref}`);
  return fragment.slice(8);
}
const metadata = ['$schema', '$id', 'x-spdx', 'title', 'description', '$defs'];
function check(node, path, named = false) {
  if (!node || typeof node !== 'object' || Array.isArray(node)) fail(`${path} must be a schema object`);
  const keys = ['description', ...(registry.get(node.$id) === node ? metadata : []), ...(node.$ref ? ['$ref'] : {
    object: ['type', 'properties', 'required', 'additionalProperties'],
    string: ['type', 'enum', 'minLength', 'pattern'],
    integer: ['type', 'enum', 'minimum', 'maximum'],
    number: ['type', 'minimum', 'maximum'], boolean: ['type'],
    array: ['type', 'items', 'prefixItems', 'minItems', 'maxItems'],
  }[node.type] ?? fail(`${path} has unknown type`))];
  for (const key of Object.keys(node)) if (!keys.includes(key)) fail(`${path}.${key}`);
  if (node.$ref) {
    reference(node);
    if (Object.keys(node).some(key => key !== '$ref')) fail(`${path} reference siblings`);
    return;
  }
  if (node.enum) {
    if (!named || !Array.isArray(node.enum) || !node.enum.length || new Set(node.enum).size !== node.enum.length) fail(`${path} enum`);
    if (node.type === 'string' && node.enum.some(value => typeof value !== 'string' || !/^[a-z][a-z0-9_]*$/.test(value))) fail(`${path} enum identifiers`);
    if (node.type === 'integer' && node.enum.some(value => !numberNames[value])) fail(`${path} integer enum value`);
  }
  for (const key of ['minimum', 'maximum', 'minLength', 'minItems', 'maxItems']) {
    if (key in node && (!Number.isFinite(node[key]) || (key.startsWith('min') && key !== 'minimum' && (!Number.isInteger(node[key]) || node[key] < 0)))) fail(`${path}.${key}`);
  }
  if (node.pattern) { if (typeof node.pattern !== 'string') fail(`${path}.pattern`); new RegExp(node.pattern); }
  if (node.type === 'object') {
    if (!named || node.additionalProperties !== false || !node.properties || !Array.isArray(node.required)) fail(`${path} must be a closed named object`);
    const names = Object.keys(node.properties);
    if (!names.length || names.some(key => !/^[a-z][a-z0-9_]*$/.test(key)) || names.length !== node.required.length || new Set(node.required).size !== names.length || names.some(key => !node.required.includes(key))) fail(`${path} requires all properties exactly once`);
    for (const [key, value] of entries(node.properties)) check(value, `${path}.${key}`);
  }
  if (node.type === 'array') {
    if (node.prefixItems) {
      if (!named || node.minItems !== 2 || node.maxItems !== 2 || node.items !== false || node.prefixItems.length !== 2 || JSON.stringify(node.prefixItems[0]) !== JSON.stringify(node.prefixItems[1])) fail(`${path} fixed homogeneous pair`);
      if (node.prefixItems[0].type !== 'integer' || node.prefixItems[0].minimum !== 0 || node.prefixItems[0].maximum !== 4294967295) fail(`${path} portable unsigned offset`);
      node.prefixItems.forEach((value, index) => check(value, `${path}[${index}]`));
    } else {
      if ('minItems' in node || 'maxItems' in node || !node.items || typeof node.items !== 'object') fail(`${path} array constraints`);
      check(node.items, `${path}[]`);
    }
  }
  if (node.type === 'integer' && !node.enum && (node.minimum !== 0 || !Number.isSafeInteger(node.maximum) || node.maximum < 0)) fail(`${path} requires portable unsigned integer bounds`);
}
for (const [name, value] of entries(definitions)) {
  if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) fail(`type name ${name}`);
  check(value, name, true);
}
// Recursive declarations are outside this deliberately small binding subset.
// Reject them before emitting code that some target languages cannot compile.
const visiting = new Set(), visited = new Set();
function checkReferences(name) {
  if (visiting.has(name)) fail(`cyclic reference ${name}`);
  if (visited.has(name)) return;
  visiting.add(name);
  function walk(node) {
    if (!node || typeof node !== 'object') return;
    if (node.$ref) checkReferences(reference(node));
    else for (const [key, value] of entries(node)) if (key !== '$defs') walk(value);
  }
  walk(definitions[name]);
  visiting.delete(name);
  visited.add(name);
}
for (const name of Object.keys(definitions)) checkReferences(name);
function type(node, lang) {
  if (node.$ref) return reference(node);
  const basic = {
    string: { rust: 'String', ts: 'string', kt: 'String', swift: 'String' },
    integer: { rust: 'u64', ts: 'number', kt: 'Long', swift: 'UInt64' },
    number: { rust: 'f64', ts: 'number', kt: 'Double', swift: 'Double' },
    boolean: { rust: 'bool', ts: 'boolean', kt: 'Boolean', swift: 'Bool' },
  }[node.type];
  if (basic) return basic[lang];
  if (node.type === 'array') {
    if (node.prefixItems) return { rust: '[usize; 2]', ts: '[number, number]', kt: 'List<Long>', swift: '[UInt64]' }[lang];
    const element = type(node.items, lang);
    return { rust: `Vec<${element}>`, ts: `${element}[]`, kt: `List<${element}>`, swift: `[${element}]` }[lang];
  }
  fail(`unhandled ${node.type}`);
}
function emit(name, node, lang) {
  if (node.enum) {
    const values = node.enum;
    const names = values.map(value => node.type === 'string' ? pascal(value) : numberNames[value]);
    if (lang === 'ts') return `export type ${name} = ${values.map(quote).join(' | ')};`;
    if (lang === 'rust') {
      const attr = node.type === 'string' ? '#[serde(rename_all = "snake_case")]' : '#[serde(try_from = "u8", into = "u8")]';
      let output = `#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\n${attr}\npub enum ${name} {\n${names.map(value => `    ${value},`).join('\n')}\n}`;
      if (node.type === 'integer') output += `\nimpl From<${name}> for u8 {\n    fn from(value: ${name}) -> Self {\n        match value {\n${names.map((value, index) => `            ${name}::${value} => ${values[index]},`).join('\n')}\n        }\n    }\n}\nimpl TryFrom<u8> for ${name} {\n    type Error = &'static str;\n    fn try_from(value: u8) -> Result<Self, Self::Error> {\n        match value {\n${names.map((value, index) => `            ${values[index]} => Ok(Self::${value}),`).join('\n')}\n            _ => Err("invalid ${name}"),\n        }\n    }\n}`;
      return output;
    }
    if (lang === 'swift') return `public enum ${name}: ${node.type === 'string' ? 'String' : 'Int'}, Codable, Sendable {\n${names.map((value, index) => `    case ${value[0].toLowerCase() + value.slice(1)} = ${quote(values[index])}`).join('\n')}\n}`;
    if (node.type === 'string') return `@Serializable\npublic enum class ${name} {\n${names.map((value, index) => `    @SerialName(${quote(values[index])}) ${value.toUpperCase()},`).join('\n')}\n}`;
    return `@Serializable(with = ${name}Serializer::class)\npublic enum class ${name}(public val wireValue: Int) { ${names.map((value, index) => `${value.toUpperCase()}(${values[index]})`).join(', ')} }\npublic object ${name}Serializer : KSerializer<${name}> {\n    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("${name}", PrimitiveKind.INT)\n    override fun serialize(encoder: Encoder, value: ${name}) = encoder.encodeInt(value.wireValue)\n    override fun deserialize(decoder: Decoder): ${name} {\n        val value = decoder.decodeInt()\n        return ${name}.entries.firstOrNull { it.wireValue == value } ?: throw SerializationException("Invalid ${name}")\n    }\n}`;
  }
  if (node.type !== 'object') return { rust: `pub type ${name} = ${type(node, lang)};`, ts: `export type ${name} = ${type(node, lang)};`, kt: `public typealias ${name} = ${type(node, lang)}`, swift: `public typealias ${name} = ${type(node, lang)}` }[lang];
  const props = entries(node.properties);
  if (lang === 'rust') return `#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n${props.map(([key, value]) => `    pub ${key}: ${type(value, lang)},`).join('\n')}\n}`;
  if (lang === 'ts') return `export interface ${name} {\n${props.map(([key, value]) => `  ${key}: ${type(value, lang)};`).join('\n')}\n}`;
  if (lang === 'kt') return `@Serializable\npublic data class ${name}(\n${props.map(([key, value]) => `    public val ${key}: ${type(value, lang)},`).join('\n')}\n)`;
  return `public struct ${name}: Codable, Sendable {\n${props.map(([key, value]) => `    public let ${key}: ${type(value, lang)}`).join('\n')}\n    public init(${props.map(([key, value]) => `${key}: ${type(value, lang)}`).join(', ')}) {\n${props.map(([key]) => `        self.${key} = ${key}`).join('\n')}\n    }\n}`;
}
const outputs = {
  rust: ['core/schema/src/generated.rs', ''], ts: ['packages/protocol/generated/suggestion.ts', ''],
  kt: ['packages/protocol/generated/Suggestion.kt', 'package app.nexwrite.protocol\n\nimport kotlinx.serialization.*\nimport kotlinx.serialization.descriptors.*\nimport kotlinx.serialization.encoding.*\n\n'],
  swift: ['packages/protocol/generated/Suggestion.swift', 'import Foundation\n\n'],
};
const checkOnly = process.argv.slice(2).includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node tools/codegen/generate.mjs [--check]');
let stale = false;
for (const [lang, [path, prelude]] of entries(outputs)) {
  const content = header + prelude + entries(definitions).map(([name, node]) => emit(name, node, lang)).join('\n\n') + '\n';
  const target = resolve(root, path);
  if (checkOnly) {
    let actual; try { actual = await readFile(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (actual !== content) { process.stderr.write(`Stale generated binding: ${path}\n`); stale = true; }
  } else { await mkdir(dirname(target), { recursive: true }); await writeFile(target, content); }
}
if (stale) process.exitCode = 1;
else process.stdout.write(checkOnly ? 'Generated bindings match canonical schema.\n' : 'Generated Rust, TypeScript, Kotlin, and Swift bindings.\n');
