// This deliberately bounded OpenAPI generator emits DTOs, not an HTTP SDK.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const canonicalBase = 'https://nexwrite.local/schema/';
export const validationId = `${canonicalBase}owned-api.schema.json`;
const names = ['ApiLocale', 'AiTask', 'AiPreset', 'HealthResponse', 'EngineCapabilities', 'ProviderProfile', 'Capabilities', 'AnalyzeRequest', 'RewriteRequest', 'AiResult', 'ApiProblem'];
const canonicalRefs = new Map([
  ['../../packages/protocol/schema/analysis.schema.json', 'AnalysisResult'],
  ['../../packages/protocol/schema/analysis.schema.json#/$defs/InputFormat', 'InputFormat'],
]);
const quote = JSON.stringify;
const fail = message => { throw new Error(`Unsupported OpenAPI contract: ${message}`); };
const identifier = /^[a-z][a-z0-9_]*$/;
const typeIdentifier = /^[A-Z][A-Za-z0-9]*$/;
const pascal = value => value.split(/[_-]/).map(part => part[0].toUpperCase() + part.slice(1)).join('');
const header = '// SPDX-License-Identifier: LicenseRef-NexWrite-Proprietary\n// Generated by tools/api-codegen.mjs. Do not edit.\n// DTOs only. Validate wire data using the closed canonical/API JSON Schema registry.\n// Types alone do not enforce const, bounds, patterns, Unicode, byte limits or conditional constraints.\n';

function reference(ref, definitions) {
  if (typeof ref !== 'string') fail('reference is not a string');
  if (canonicalRefs.has(ref)) return canonicalRefs.get(ref);
  const match = /^#\/components\/schemas\/([A-Z][A-Za-z0-9]*)$/.exec(ref);
  if (!match || !Object.hasOwn(definitions, match[1])) fail(`unregistered reference ${ref}`);
  return match[1];
}

function checkNode(node, definitions, path, named = false, conditional = false) {
  if (!node || typeof node !== 'object' || Array.isArray(node)) fail(`${path} must be a schema object`);
  const byType = {
    string: ['minLength', 'maxLength', 'pattern', 'x-utf8-max-bytes', 'x-unicode-scalar-string'],
    integer: ['minimum', 'maximum'], boolean: [], array: ['items', 'minItems', 'maxItems'],
    object: ['properties', 'required', 'additionalProperties'],
  };
  if (node.$ref) {
    if (Object.keys(node).length !== 1) fail(`${path} reference siblings`);
    reference(node.$ref, definitions);
    return;
  }
  const annotation = ['description', 'type', 'enum', 'const', 'allOf'];
  const allowed = [...annotation, ...(byType[node.type] ?? (conditional && !node.type ? ['properties', 'required'] : fail(`${path} type`)))];
  for (const key of Object.keys(node)) if (!allowed.includes(key)) fail(`${path}.${key}`);
  if (node.enum && (!Array.isArray(node.enum) || !node.enum.length || new Set(node.enum).size !== node.enum.length)) fail(`${path} enum`);
  for (const value of node.enum ?? []) {
    if (node.type === 'string' && (typeof value !== 'string' || !/^[a-zA-Z][a-zA-Z0-9_-]*$/.test(value))) fail(`${path} enum value`);
    if (node.type === 'integer' && !Number.isSafeInteger(value)) fail(`${path} integer enum`);
  }
  for (const key of ['minimum', 'maximum', 'minLength', 'maxLength', 'minItems', 'maxItems', 'x-utf8-max-bytes']) {
    if (key in node && (!Number.isSafeInteger(node[key]) || node[key] < 0)) fail(`${path}.${key}`);
  }
  if (node.minimum > node.maximum || node.minLength > node.maxLength || node.minItems > node.maxItems) fail(`${path} inverted bound`);
  if (node.pattern) { if (typeof node.pattern !== 'string') fail(`${path}.pattern`); new RegExp(node.pattern, 'u'); }
  if (node.type === 'string' && node['x-unicode-scalar-string'] !== true) fail(`${path} must reject lone surrogates`);
  if (node.type === 'object' || node.properties) {
    if ((!named && !conditional) || (!conditional && node.additionalProperties !== false) || !node.properties || typeof node.properties !== 'object') fail(`${path} must be a closed named object`);
    const keys = Object.keys(node.properties);
    if (!keys.length || keys.some(key => !identifier.test(key) || ['constructor', 'prototype', '__proto__'].includes(key))) fail(`${path} property names`);
    if (node.required && (!Array.isArray(node.required) || new Set(node.required).size !== node.required.length || node.required.some(key => !Object.hasOwn(node.properties, key)))) fail(`${path} required`);
    if (!conditional && !Array.isArray(node.required)) fail(`${path} missing required array`);
    for (const [key, value] of Object.entries(node.properties)) checkNode(value, definitions, `${path}.${key}`, false, conditional);
  }
  if (node.type === 'array') {
    if (!node.items) fail(`${path} missing items`);
    checkNode(node.items, definitions, `${path}[]`);
  }
  if ('const' in node) {
    if (node.type === 'array') {
      if (!Array.isArray(node.const)) fail(`${path} array const`);
    } else if (node.type === 'integer' ? !Number.isSafeInteger(node.const) : node.type && typeof node.const !== node.type) fail(`${path} const type`);
  }
  if (node.allOf) {
    if (!Array.isArray(node.allOf) || node.allOf.length !== 1) fail(`${path} allOf`);
    const condition = node.allOf[0];
    if (!condition || Object.keys(condition).sort().join(',') !== 'if,then') fail(`${path} condition`);
    checkNode(condition.if, definitions, `${path}.if`, false, true);
    checkNode(condition.then, definitions, `${path}.then`, false, true);
  }
}

export function validateContract(document) {
  if (document.openapi !== '3.1.0' || document.jsonSchemaDialect !== 'https://json-schema.org/draft/2020-12/schema' || document['x-spdx'] !== 'LicenseRef-NexWrite-Proprietary') fail('root metadata');
  const definitions = document.components?.schemas;
  if (!definitions || Object.keys(definitions).sort().join(',') !== [...names].sort().join(',')) fail('unexpected schema registry');
  for (const [name, node] of Object.entries(definitions)) {
    if (!typeIdentifier.test(name) || ['constructor', 'prototype', '__proto__'].includes(name)) fail('unsafe type name');
    checkNode(node, definitions, name, true);
  }
  const requiredPaths = { '/health': 'get', '/v1/capabilities': 'get', '/v1/analyze': 'post', '/v1/rewrite': 'post' };
  const responseTypes = { '/health': '#/components/schemas/HealthResponse', '/v1/capabilities': '#/components/schemas/Capabilities', '/v1/analyze': '../../packages/protocol/schema/analysis.schema.json', '/v1/rewrite': '#/components/schemas/AiResult' };
  if (Object.keys(document.paths ?? {}).sort().join(',') !== Object.keys(requiredPaths).sort().join(',')) fail('unexpected paths');
  for (const [path, method] of Object.entries(requiredPaths)) {
    if (Object.keys(document.paths[path]).join(',') !== method) fail(`${path} method`);
    const operation = document.paths[path][method];
    const response = operation.responses?.['200']?.content?.['application/json']?.schema;
    if (!response || response.$ref !== responseTypes[path]) fail(`${path} success contract`);
    checkNode(response, definitions, `${path} success`);
    if (method === 'post') {
      const request = operation.requestBody?.content?.['application/json']?.schema;
      if (operation.requestBody.required !== true || request?.$ref !== `#/components/schemas/${path === '/v1/analyze' ? 'AnalyzeRequest' : 'RewriteRequest'}`) fail(`${path} request contract`);
      checkNode(request, definitions, `${path} request`);
    }
  }
  function checkAllReferences(node) {
    if (!node || typeof node !== 'object') return;
    if (node.$ref && node.$ref !== '#/components/responses/Problem') reference(node.$ref, definitions);
    for (const value of Object.values(node)) checkAllReferences(value);
  }
  checkAllReferences(document);
  // Bindings intentionally reuse canonical declarations; no network resolver is present.
  return definitions;
}

function wireType(node, lang, definitions) {
  if (node.$ref) return reference(node.$ref, definitions);
  if (lang === 'ts' && Object.hasOwn(node, 'const')) return quote(node.const);
  if (lang === 'ts' && node.enum) return node.enum.map(quote).join(' | ');
  const basic = { string: { ts: 'string', kt: 'String', swift: 'String' }, integer: { ts: 'number', kt: 'Long', swift: 'UInt64' }, boolean: { ts: 'boolean', kt: 'Boolean', swift: 'Bool' } }[node.type];
  if (basic) return basic[lang];
  if (node.type === 'array') {
    const item = wireType(node.items, lang, definitions);
    return { ts: `(${item})[]`, kt: `List<${item}>`, swift: `[${item}]` }[lang];
  }
  fail(`cannot emit ${node.type}`);
}

function emit(name, node, lang, definitions) {
  if (node.enum && node.type === 'string') {
    if (lang === 'ts') return `export type ${name} = ${node.enum.map(quote).join(' | ')};`;
    if (lang === 'kt') return `@Serializable\npublic enum class ${name} {\n${node.enum.map(value => `    @SerialName(${quote(value)}) ${value.replaceAll('-', '_').toUpperCase()},`).join('\n')}\n}`;
    return `public enum ${name}: String, Codable, Sendable {\n${node.enum.map(value => { const p = pascal(value); return `    case ${p[0].toLowerCase() + p.slice(1)} = ${quote(value)}`; }).join('\n')}\n}`;
  }
  if (node.type !== 'object') fail(`named type ${name} must be enum or object`);
  const properties = Object.entries(node.properties);
  const required = new Set(node.required);
  if (lang === 'ts') return `export interface ${name} {\n${properties.map(([key, value]) => `  ${key}${required.has(key) ? '' : '?'}: ${wireType(value, lang, definitions)};`).join('\n')}\n}`;
  if (lang === 'kt') return `@Serializable\npublic data class ${name}(\n${properties.map(([key, value]) => `    public val ${key}: ${wireType(value, lang, definitions)}${required.has(key) ? '' : '? = null'},`).join('\n')}\n)`;
  const fieldType = (key, value) => wireType(value, lang, definitions) + (required.has(key) ? '' : '?');
  return `public struct ${name}: Codable, Sendable {\n${properties.map(([key, value]) => `    public let ${key}: ${fieldType(key, value)}`).join('\n')}\n    public init(${properties.map(([key, value]) => `${key}: ${fieldType(key, value)}${required.has(key) ? '' : ' = nil'}`).join(', ')}) {\n${properties.map(([key]) => `        self.${key} = ${key}`).join('\n')}\n    }\n}`;
}

export function buildOutputs(document) {
  const definitions = validateContract(document);
  const runtime = JSON.parse(JSON.stringify(definitions));
  function rewrite(node) {
    if (!node || typeof node !== 'object') return;
    if (node.$ref) {
      const name = reference(node.$ref, definitions);
      node.$ref = canonicalRefs.has(node.$ref) ? `${canonicalBase}analysis.schema.json${name === 'AnalysisResult' ? '' : `#/$defs/${name}`}` : `#/$defs/${name}`;
    }
    for (const value of Object.values(node)) rewrite(value);
  }
  rewrite(runtime);
  const files = Object.create(null);
  for (const [lang, prelude] of Object.entries({ ts: "import type { AnalysisResult, InputFormat } from '@nexwrite/protocol';\nexport type { AnalysisResult };\n\n", kt: 'package app.nexwrite.protocol\n\nimport kotlinx.serialization.*\n\n', swift: 'import Foundation\n\n' })) {
    files[`owned-api.${lang === 'ts' ? 'ts' : lang === 'kt' ? 'kt' : 'swift'}`] = header + prelude + Object.entries(definitions).map(([name, node]) => emit(name, node, lang, definitions)).join('\n\n') + '\n';
  }
  files['validation.schema.json'] = JSON.stringify({ $schema: document.jsonSchemaDialect, $id: validationId, 'x-spdx': 'LicenseRef-NexWrite-Proprietary', description: 'Generated API schema registry. Register canonical analysis.schema.json and suggestion.schema.json locally; do not fetch references. Enforce custom Unicode/UTF-8 keywords. DTOs are not validators.', $defs: runtime }, null, 2) + '\n';
  return files;
}

async function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node tools/api-codegen.mjs [--check]');
  const document = JSON.parse(await readFile(resolve(root, 'docs/api/owned-app.openapi.json'), 'utf8'));
  const files = buildOutputs(document);
  let stale = false;
  for (const [name, output] of Object.entries(files)) {
    const path = resolve(root, 'packages/protocol/api-generated', name);
    if (process.argv.includes('--check')) {
      let current; try { current = await readFile(path, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (current !== output) { process.stderr.write(`Stale API artifact: ${name}\n`); stale = true; }
    } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, output); }
  }
  if (stale) process.exitCode = 1;
  else process.stdout.write(process.argv.includes('--check') ? 'API contract artifacts match.\n' : 'Generated API DTO bindings and runtime registry.\n');
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
